n1 = int(input('enter your first number: '))
n2 = int(input('enter your second number: '))

print('num1 and num2 = ',n1 & n2)


print('\n num1  | num2 = ', n1 | n2)


print('\n ~ num1= ', ~n1)

print('\n ~ num2= ', ~n2)

print('\n num1 ^ num2 = ', n1 ^ n2)


print('\n num1 >> 1 = ', n1 >> 1)


print('\n num2 >> 1 = ', n2 >> 1)


print('\n num1 << 1 = ', n1 << 1)


print('\n num2 << 1 = ', n2 << 1)
